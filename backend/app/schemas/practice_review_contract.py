class AnswerStrengthItem(StrictSchema):
    """A verified strength observed in the candidate's answer."""
    dimension: str = Field(..., min_length=1, max_length=50)
    observation: str = Field(..., min_length=5, max_length=500)
    answer_segment_ids: List[str] = Field(default_factory=list, max_length=10)


class ImprovementAreaItem(StrictSchema):
    """A constructive gap or missing element identified in the candidate's response."""
    dimension: str = Field(..., min_length=1, max_length=50)
    observation: str = Field(..., min_length=5, max_length=500)
    answer_segment_ids: List[str] = Field(default_factory=list, max_length=10)


class FollowUpItem(StrictSchema):
    """At most one follow-up question when materially beneficial."""
    needed: bool = False
    question: Optional[str] = Field(None, max_length=500)


class ConversationalReviewPayload(StrictSchema):
    """Strict structured conversational answer review generated by local AI."""
    schema_version: str = Field(default=PRACTICE_ANSWER_REVIEW_SCHEMA_VERSION)
    source_question_id: str = Field(..., min_length=1, max_length=64)
    answer_status: AnswerStatus = AnswerStatus.ASSESSABLE
    acknowledgement: str = Field(..., min_length=5, max_length=300)
    strengths: List[AnswerStrengthItem] = Field(default_factory=list, max_length=2)
    improvement_areas: List[ImprovementAreaItem] = Field(default_factory=list, max_length=3)
    next_steps: List[str] = Field(default_factory=list, min_length=2, max_length=3)
    stronger_structure: str = Field(..., min_length=10, max_length=500)
    dimension_levels: Dict[str, DimensionLevel] = Field(default_factory=dict)
    follow_up: FollowUpItem = Field(default_factory=lambda: FollowUpItem(needed=False, question=None))
    uncertainty_codes: List[str] = Field(default_factory=list)

    @field_validator("next_steps")
    @classmethod
    def validate_next_steps_items(cls, steps: List[str]) -> List[str]:
        for s in steps:
            if not s or len(s.strip()) < 5:
                raise ValueError("Next step items must contain meaningful actionable advice.")
        return steps


class McqReviewPayload(StrictSchema):
    """MCQ review schema computed deterministically server-side with optional local explanation."""
    schema_version: str = Field(default=PRACTICE_MCQ_REVIEW_SCHEMA_VERSION)
    source_question_id: str = Field(..., min_length=1, max_length=64)
    selected_option_id: str = Field(..., min_length=1, max_length=64)
    correct_option_id: Optional[str] = Field(None, max_length=64)
    is_correct: bool
    explanation: Optional[str] = Field(None, max_length=1000)
    selected_option_review: Optional[str] = Field(None, max_length=500)
    learning_point: Optional[str] = Field(None, max_length=500)
    competency: Optional[str] = Field(None, max_length=200)


