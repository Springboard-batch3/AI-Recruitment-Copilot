class StrengthAreaItem(StrictSchema):
    """Demonstrated strength observation in the summary."""
    title: str = Field(..., min_length=3, max_length=150)
    observation: str = Field(..., min_length=5, max_length=500)
    source_review_ids: List[str] = Field(default_factory=list, max_length=10)


class PriorityImprovementItem(StrictSchema):
    """Priority improvement area observation in the summary."""
    title: str = Field(..., min_length=3, max_length=150)
    observation: str = Field(..., min_length=5, max_length=500)
    source_review_ids: List[str] = Field(default_factory=list, max_length=10)


class CompetencyCommentaryItem(StrictSchema):
    """Qualitative commentary on a specific competency."""
    competency_id: str = Field(..., min_length=1, max_length=150)
    commentary: str = Field(..., min_length=5, max_length=500)
    source_review_ids: List[str] = Field(default_factory=list, max_length=10)


class ResponsePatternItem(StrictSchema):
    """Observation regarding recurring response patterns."""
    observation: str = Field(..., min_length=5, max_length=500)
    source_review_ids: List[str] = Field(default_factory=list, max_length=10)


class PracticeCoachingSummaryPayload(StrictSchema):
    """Strict structured final coaching summary generated by local AI."""
    schema_version: str = Field(default=PRACTICE_COACHING_SUMMARY_SCHEMA_VERSION)
    summary: str = Field(..., min_length=10, max_length=1000)
    strongest_areas: List[StrengthAreaItem] = Field(default_factory=list, max_length=3)
    priority_improvements: List[PriorityImprovementItem] = Field(default_factory=list, max_length=3)
    competency_commentary: List[CompetencyCommentaryItem] = Field(default_factory=list, max_length=10)
    response_patterns: List[ResponsePatternItem] = Field(default_factory=list, max_length=5)
    next_practice_plan: List[str] = Field(..., min_length=3, max_length=3)
    disclaimer: str = Field(default="This is practice coaching and not a hiring decision.")

    @field_validator("next_practice_plan")
    @classmethod
    def validate_plan_items(cls, items: List[str]) -> List[str]:
        for item in items:
            if not item or len(item.strip()) < 5:
                raise ValueError("Each next practice action item must contain actionable advice.")
        return items


